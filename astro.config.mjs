// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';
import { baseLinks } from './src/lib/base-links.mjs';

// Sidebar sections follow the wiki structure in docs/master-prompt.md (sections A–S).
/** @param {string} label @param {string} directory */
const section = (label, directory) => ({ label, collapsed: true, items: [{ autogenerate: { directory } }] });

// ---- Deployment settings (see docs/deployment.md) ----
// Published on GitHub Pages at https://avie-dev.github.io/sangriaGuide/. SITE is the origin and BASE
// the sub-path; both are used for the sitemap, canonical URLs, social previews and every internal
// link. Override with SITE_URL and BASE_PATH (e.g. BASE_PATH=/ for a custom domain).
const SITE = process.env.SITE_URL || 'https://avie-dev.github.io';
const BASE = process.env.BASE_PATH || '/sangriaGuide';
const basePrefix = BASE.replace(/\/$/, '');
// The GitHub repository. Every page gets an "Edit page" link and the contribute page links to the
// issue templates. REPO_URL overrides it at build time (an empty REPO_URL turns the links off).
const REPO = process.env.REPO_URL ?? 'https://github.com/avie-dev/sangriaGuide';

export default defineConfig({
	site: SITE,
	base: BASE,
	trailingSlash: 'always',
	// Lets components link to the repository (src/components/RepoLink.astro).
	vite: { define: { 'import.meta.env.PUBLIC_REPO_URL': JSON.stringify(REPO) } },
	integrations: [
		// Articles write internal links from the site root; this adds the base path at build time.
		// Must come before Starlight so the link validator sees the final links.
		baseLinks(BASE),
		starlight({
			title: 'Sangria Falls Wiki',
			// Fails the build on broken internal links and anchors in articles.
			// Open-question anchors are generated by the OpenQuestions component, which the validator can't see.
			plugins: [starlightLinksValidator({ exclude: [`${basePrefix}/about/open-questions/#q-+([0-9])`] })],
			description:
				'Unofficial, English-first community wiki for the Sangria Falls V Rising server: from your first login to endgame.',
			lastUpdated: true,
			favicon: '/favicon.svg',
			...(REPO ? { editLink: { baseUrl: `${REPO.replace(/\/$/, '')}/edit/main/` } } : {}),
			routeMiddleware: './src/routeData.ts',
			customCss: [
				'@fontsource/cinzel/600.css',
				'@fontsource/cinzel/700.css',
				'@fontsource-variable/inter',
				'./src/styles/theme.css',
			],
			components: {
				// Dark mode by default; a stored choice still wins.
				ThemeProvider: './src/components/overrides/ThemeProvider.astro',
				// Unofficial-site notice on every page.
				Footer: './src/components/overrides/Footer.astro',
				// Labels and work-in-progress notice under the title.
				PageTitle: './src/components/overrides/PageTitle.astro',
				// Official sources and last-verified date at the end of each article.
				MarkdownContent: './src/components/overrides/MarkdownContent.astro',
			},
			head: [
				{ tag: 'meta', attrs: { name: 'theme-color', content: '#14110f' } },
				{ tag: 'meta', attrs: { property: 'og:site_name', content: 'Sangria Falls Wiki (unofficial)' } },
			],
			sidebar: [
				{
					label: 'About this wiki',
					items: ['about', 'about/labels', 'about/sources', 'about/open-questions', 'about/contributing', 'about/changelog', 'about/components'],
				},
				section('Getting started', 'getting-started'),
				section('Progression walkthrough', 'walkthrough'),
				section('Character progression', 'character'),
				section('Meditation', 'meditation'),
				section('Classes', 'classes'),
				section('Equipment and builds', 'equipment'),
				section('Pets and Sangrulhos', 'companions'),
				section('Professions', 'professions'),
				section('Economy', 'economy'),
				section('Dungeons', 'dungeons'),
				section('Events', 'events'),
				section('Outposts and quests', 'quests'),
				section('Vampiric Schools', 'schools'),
				section('Endgame', 'endgame'),
				section('Battle Pass and VIP', 'support'),
				section('World and community', 'world'),
				section('Reference', 'reference'),
				section('Tools', 'tools'),
			],
		}),
	],
});
